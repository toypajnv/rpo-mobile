def _neutralize_value(value: Any) -> Any:
    if isinstance(value, list):
        return [_neutralize_value(item) for item in value]
    if isinstance(value, str):
        return LEGACY_LABELS.get(value, value)
    return value


_original_answer_dict = _survey._answer_dict


def _answer_dict(row):
    return {key: _neutralize_value(value) for key, value in _original_answer_dict(row).items()}


def _readiness_index(rows) -> int:
    if not rows:
        return 0

    scores: list[float] = []
    q1_map = {
        "Сразу останавливаю работу / прошу прекратить опасное действие": 100,
        "Делаю замечание, но работу не останавливаю": 75,
        "Сообщаю своему руководителю": 50,
        "Сообщаю ответственному руководителю": 50,
        "Прохожу мимо, если нарушение не кажется серьёзным": 25,
        "Ничего не делаю": 0,
    }
    q5_map = {
        "Сам остановлю работу": 100,
        "Сделаю замечание и попрошу устранить нарушение": 80,
        "Позвоню своему руководителю": 60,
        "Сообщу ответственному руководителю": 60,
        "Подожду, пока придёт ответственный": 30,
        "Скорее всего, не буду вмешиваться": 0,
    }
    q6_map = {"Да, хорошо знаю": 100, "Примерно знаю": 60, "Не знаю": 0}
    q13_map = {
        "Полностью согласен": 100,
        "Скорее согласен": 75,
        "Скорее не согласен": 25,
        "Не согласен": 0,
    }

    for row in rows:
        answers = _answer_dict(row)
        local: list[float] = []
        q1 = _survey._normalize_other(_survey._clean_text(answers.get("q1")))
        if q1 in q1_map:
            local.append(q1_map[q1])
        q3 = _survey._clean_text(answers.get("q3"))
        if q3 in {"1", "2", "3", "4", "5"}:
            local.append((int(q3) - 1) * 25)
        q5 = _survey._normalize_other(_survey._clean_text(answers.get("q5")))
        if q5 in q5_map:
            local.append(q5_map[q5])
        q6 = _survey._clean_text(answers.get("q6"))
        if q6 in q6_map:
            local.append(q6_map[q6])
        q13 = _survey._clean_text(answers.get("q13"))
        if q13 in q13_map:
            local.append(q13_map[q13])
        if local:
            scores.append(sum(local) / len(local))

    return round(sum(scores) / len(scores)) if scores else 0


